-- Independent read-only visual matching support for RA WhatsApp Lab.
-- Raw client photographs are processed transiently, never stored.
CREATE TABLE IF NOT EXISTS public.ra_catalog_visual_index (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  negocio_id uuid NOT NULL,
  producto_id bigint NOT NULL REFERENCES public.productos(id) ON DELETE CASCADE,
  variante_id bigint REFERENCES public.producto_variantes(id) ON DELETE CASCADE,
  foto_num smallint NOT NULL CHECK (foto_num IN (1, 2)),
  foto_url text NOT NULL,
  signature jsonb,
  estado text NOT NULL CHECK (estado IN ('indexed', 'error')),
  actualizado_en timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ra_catalog_visual_index_unique
    UNIQUE NULLS NOT DISTINCT (negocio_id, producto_id, variante_id, foto_num)
);

CREATE INDEX IF NOT EXISTS ra_catalog_visual_negocio_idx
  ON public.ra_catalog_visual_index (negocio_id, estado);

ALTER TABLE public.ra_catalog_visual_index ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.ra_catalog_visual_index FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.ra_catalog_visual_index TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.ra_catalog_visual_index_id_seq TO service_role;
COMMENT ON TABLE public.ra_catalog_visual_index IS
  'Huellas visuales aproximadas de imagenes RA; no se almacenan fotos de clientes.';
